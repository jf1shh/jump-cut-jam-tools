#!/usr/bin/env python3
"""GEN 1 import in one command: finished gen1 outputs -> concept board + UE staging import.

    python3 scripts/gen1_import.py                      # import everything finished (editor must be CLOSED)
    python3 scripts/gen1_import.py --dry-run            # list what it would do, touch nothing
    python3 scripts/gen1_import.py --placeholder X.glb --dest /Game/Staging/_dryrun/ --cleanup   # self-test

1. Concepts: work/generated/concepts/*/concept.png (+ sidecar) -> stages/02_build/output/gen1-concept-board.md,
   gpt and fal side by side per direction and subject.
2. Props: work/generated/<NAME>/<NAME>.glb with its .glb.provenance.json -> headless UnrealEditor-Cmd (windowless,
   no display) runs scripts/ue_gen1_batch.py: import, collision, LOD, PBR check, then size/pivot/collision check.
   Props land under /Game/Staging/Gen1/. Rodin props (name ends _rodin) land under /Game/Staging/Hold/ and are
   marked HOLD: shipping one waits for the owner's OK. Props with no sidecar are refused (provenance is mandatory).
3. Provenance is copied to <game>/work/gen1-import/ and the report goes to stages/02_build/output/gen1-import-report.md.
Exit 0 = every prop imported with no warnings, 1 = errors or warnings (read the report), 2 = refused.
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENGINE = Path.home() / "Projects/UnrealEngine-5.9/Engine/Binaries/Linux/UnrealEditor-Cmd"
GAME = Path.home() / "Projects/megajam-game"
GEN = ROOT / "work/generated"
BOARD = ROOT / "stages/02_build/output/gen1-concept-board.md"
REPORT = ROOT / "stages/02_build/output/gen1-import-report.md"
RUN = subprocess.run  # tests swap this for a fake
TIMEOUT = 420  # the batch script quits the editor itself; this only catches a hang


def concepts(gen=GEN):
    """{(direction, subject): {provider: (png, sidecar)}} from concept_<D>_<subject>_<provider> folders."""
    out = {}
    for d in sorted((gen / "concepts").glob("concept_*")):
        png = d / "concept.png"
        parts = d.name.split("_")  # concept, D, subject..., provider
        if not png.exists() or len(parts) < 4:
            continue
        key = (parts[1], "_".join(parts[2:-1]))
        out.setdefault(key, {})[parts[-1]] = (png, d / "concept.png.provenance.json")
    return out


def write_board(found, path=BOARD, base=None):
    base = base or path.parent
    lines = ["# GEN 1 concept board", "", "Generated by scripts/gen1_import.py. Concepts only: AI-generated, not sourced assets.", ""]
    for (d, subj), provs in sorted(found.items()):
        lines += [f"## Direction {d}: {subj}", "", "| " + " | ".join(sorted(provs)) + " |", "|" + "---|" * len(provs)]
        cells = [f"![{p}]({os.path.relpath(provs[p][0], base)})" for p in sorted(provs)]
        lines += ["| " + " | ".join(cells) + " |", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))
    return len(found)


# Props whose albedo atlas has stray letters/badges: import with a plain colour instead (hub-informed 2026-11-12).
FLAT_COLOURS = {"Barrel": (0.07, 0.075, 0.08, 1.0), "PropTruck": (0.14, 0.13, 0.11, 1.0),
                "ClapperSign": (0.012, 0.012, 0.014, 1.0)}


def flatten_glb(src, dst, rgba):
    """Write a copy of a GLB with every base-colour texture removed and a plain baseColorFactor. Normal/AO kept."""
    import struct
    b = Path(src).read_bytes()
    magic, ver, _ = struct.unpack("<4sII", b[:12])
    if magic != b"glTF":
        raise ValueError(f"{src}: not a GLB")
    jlen, jtype = struct.unpack("<I4s", b[12:20])
    doc = json.loads(b[20:20 + jlen])
    rest = b[20 + jlen:]
    for m in doc.get("materials", []):
        pbr = m.setdefault("pbrMetallicRoughness", {})
        pbr.pop("baseColorTexture", None)
        pbr["baseColorFactor"] = list(rgba)
        pbr["metallicFactor"] = pbr.get("metallicFactor", 0.0)
        pbr["roughnessFactor"] = 0.8
        pbr.pop("metallicRoughnessTexture", None)
    j = json.dumps(doc, separators=(",", ":")).encode()
    j += b" " * (-len(j) % 4)
    out = struct.pack("<4sII", b"glTF", ver, 12 + 8 + len(j) + len(rest)) + struct.pack("<I4s", len(j), jtype) + j + rest
    Path(dst).write_bytes(out)
    return dst


def props(gen=GEN, placeholder=None):
    """[{name, glb, sidecar, hold}] for finished props. A prop without a sidecar is returned with sidecar=None."""
    if placeholder:
        g = Path(placeholder)
        return [{"name": "Placeholder", "glb": g, "sidecar": None, "hold": False, "placeholder": True}]
    out = []
    for d in sorted(gen.glob("SM_*")):
        glb = d / f"{d.name}.glb"
        if not glb.exists():
            continue
        side = d / f"{d.name}.glb.provenance.json"
        flat = FLAT_COLOURS.get(d.name[3:])
        if flat:
            glb = flatten_glb(glb, d / f"{d.name}.flat.glb", flat)
        out.append({"name": d.name[3:], "glb": glb, "sidecar": side if side.exists() else None,
                    "hold": d.name.endswith("_rodin"), "flat": bool(flat)})
    return out


def refused(items):
    return [f"{i['name']}: no provenance sidecar" for i in items if not i["sidecar"] and not i.get("placeholder")]


def run_editor(items, dest, game=GAME, work=None, run=None):
    run = run or RUN
    work = Path(work or ROOT / "work/gen1-import")
    work.mkdir(parents=True, exist_ok=True)
    result = work / "result.json"
    result.unlink(missing_ok=True)
    man = {"dest": dest, "result": str(result),
           "items": [{"name": i["name"], "glb": str(i["glb"]), "hold": i["hold"],
                      "allow_flat": bool(i.get("flat"))} for i in items]}
    # Rodin items are imported to a separate folder by a second run so the HOLD folder is never mixed with the rest
    mp = work / "manifest.json"
    mp.write_text(json.dumps(man))
    env = dict(os.environ, GEN1_SCRIPTS=str(ROOT / "scripts"), GEN1_MANIFEST=str(mp))
    cmd = [str(ENGINE), str(game / "JumpCut.uproject"),
           "-ExecCmds=py " + str(ROOT / "scripts/ue_gen1_batch.py"),
           "-unattended", "-nosplash", "-nullrhi", "-nosound", "-stdout", "-FullStdOutLogOutput",
           f"-abslog={work / 'editor.log'}"]
    # Never pipe the editor: its UnrealTraceServer helper inherits the pipes and holds them open forever.
    # Log to a file, run inside a systemd scope, wait with a timeout, then stop the scope so helpers end too.
    unit = f"megajam-gen1imp-{time.strftime('%H%M%S')}"
    scoped = ["systemd-run", "--user", "--scope", f"--unit={unit}", "-p", "MemoryHigh=26G", "-p", "MemoryMax=28G", "--"] + cmd
    logf = work / "editor.stdout.log"
    p = None
    try:
        with open(logf, "w") as lf:
            p = run(scoped, env=env, stdout=lf, stderr=subprocess.STDOUT, timeout=TIMEOUT)
    except subprocess.TimeoutExpired:
        print(f"editor hung past {TIMEOUT}s; stopping {unit}")
    finally:
        subprocess.run(["systemctl", "--user", "stop", f"{unit}.scope"], capture_output=True)
    if not result.exists():
        raise RuntimeError(f"editor wrote no result (exit {getattr(p, 'returncode', '?')}); see {work / 'editor.log'}")
    return json.loads(result.read_text())


def finish(rows, items, game=GAME, report=REPORT, placeholder=False):
    """Copy provenance next to the game, write the report. Returns (errors, warnings)."""
    side = {i["name"]: i for i in items}
    pdir = game / "work/gen1-import"
    pdir.mkdir(parents=True, exist_ok=True)
    errs = warns = 0
    lines = ["# GEN 1 import report", "", f"Run {time.strftime('%Y-%m-%d %H:%M')}"
             + (" (placeholder dry run)" if placeholder else ""), "",
             "| prop | status | size cm | pivot off base | collision | notes |", "|---|---|---|---|---|---|"]
    for r in rows:
        it = side.get(r["name"], {})
        if it.get("sidecar"):
            shutil.copy(it["sidecar"], pdir / f"SM_{r['name']}.provenance.json")
        note = "; ".join(r.get("warnings", []))
        if it.get("hold"):
            note = ("HOLD: Rodin, no shipping until the owner OK; " + note).strip("; ")
        if r.get("error"):
            errs += 1
            status = "ERROR"
            note = r["error"][:160]
        else:
            warns += bool(r.get("warnings"))
            status = "ok" if not r.get("warnings") else "WARN"
        lines.append(f"| SM_{r['name']} | {status} | {r.get('size_cm', '')} | {r.get('pivot_base_offset_cm', '')} "
                     f"| {r.get('collision_shapes', '')} | {note} |")
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text("\n".join(lines) + "\n")
    return errs, warns


def cleanup_target(game, dest):
    """Folder --cleanup may delete: strictly below /Game/Staging/ and, once resolved, inside <game>/Content/Staging.

    Raises ValueError otherwise (/Game/, /Game/Maps/, /Game/Staging/ itself, .. escapes, symlink escapes)."""
    prefix = "/Game/Staging/"
    if not dest.startswith(prefix) or not dest[len(prefix):].strip("/"):
        raise ValueError(f"--cleanup only deletes folders below {prefix}; refused dest {dest!r}")
    root = (Path(game) / "Content" / "Staging").resolve()
    target = (Path(game) / "Content" / dest[len("/Game/"):].strip("/")).resolve()
    if target == root or not target.is_relative_to(root):
        raise ValueError(f"--cleanup refuses {dest!r}: it resolves to {target}, which is not inside {root}")
    return target


def editor_open(game=GAME):
    p = subprocess.run(["pgrep", "-af", "UnrealEditor"], capture_output=True, text=True)
    return any(game.name in ln or "JumpCut" in ln for ln in p.stdout.splitlines())


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true", help="list the plan, import nothing")
    ap.add_argument("--placeholder", help="import this one GLB as SM_Placeholder instead of the gen1 outputs")
    ap.add_argument("--dest", default="/Game/Staging/Gen1/")
    ap.add_argument("--cleanup", action="store_true", help="delete the imported folder after (self-test)")
    ap.add_argument("--game", default=str(GAME))
    a = ap.parse_args(argv)
    game = Path(a.game)
    if a.cleanup:  # validate before the import so a bad --dest never costs a run, and nothing is deleted
        try:
            cleanup_target(game, a.dest)
        except ValueError as e:
            print(f"refused: {e}")
            return 2
    found = concepts()
    if not a.placeholder and not a.dry_run:
        print(f"concept board: {write_board(found)} sets -> {BOARD.relative_to(ROOT)}")
    items = props(placeholder=a.placeholder)
    bad = refused(items)
    print(f"plan: {sum(len(v) for v in found.values())} concepts, {len(items)} props, {len(bad)} refused")
    for b in bad:
        print("REFUSED", b)
    items = [i for i in items if i["sidecar"] or i.get("placeholder")]
    if a.dry_run or not items:
        for i in items:
            print("would import", i["name"], "HOLD" if i["hold"] else "")
        return 2 if bad and not items else 0
    if editor_open(game):
        print("refused: an editor has the project open; close it first (two editors on one project clash)")
        return 2
    rows = []
    for hold in (False, True):  # Rodin runs go to the Hold folder
        sub = [i for i in items if i["hold"] == hold]
        if sub:
            dest = a.dest if not hold else "/Game/Staging/Hold/"
            rows += run_editor(sub, dest, game)
    errs, warns = finish(rows, items, game, placeholder=bool(a.placeholder))
    print(f"GEN1_IMPORT_RESULT {len(rows)} props, {errs} errors, {warns} with warnings -> {REPORT.relative_to(ROOT)}")
    if a.cleanup:
        shutil.rmtree(cleanup_target(game, a.dest), ignore_errors=True)
        print("cleaned", a.dest)
    return 1 if errs or warns else 0


if __name__ == "__main__":
    sys.exit(main())
